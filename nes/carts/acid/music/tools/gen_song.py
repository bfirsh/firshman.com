# ------------------------------------------------------------------ triangle
def kick_bar(inst='tk', beats=(0, 4, 8, 12)):
    out = []
    if beats[0] != 0:
        out.append(f'r{beats[0]}')
    for i, b in enumerate(beats):
        n = (beats[i + 1] if i + 1 < len(beats) else 16) - b
        out += [f'@{inst}', 'o1', f'a{n}']
    return out + ['|']


def tri_bars(kinds):
    toks = []
    for k in kinds:
        if k == 'k':
            toks += kick_bar()
        elif k == 's':
            toks += kick_bar('tks')
        elif k == 'k3':          # break bar: kick on 1 only, then silence
            toks += ['@tk', 'o1', 'a4', 'r12', '|']
        elif k == 'kf':          # fill: kick + 16th kicks at the end
            toks += kick_bar('tk', (0, 4, 8, 12, 14, 15))
        elif k == '-':
            toks += ['r16', '|']
        elif k.startswith('sub:'):
            notes = k[4:].split(',')
            notes = [n for n in notes for _ in range(2)]   # two half-bar pulses per note
            ln = 16 // len(notes)
            toks += ['@sub'] + [t for n in notes for t in nt(n, ln)] + ['|']
        elif k == 'half':        # breakdown return: kicks on 1 and 3
            toks += kick_bar('tks', (0, 8))
    return toks


