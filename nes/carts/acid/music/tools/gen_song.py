def siren(bars_before):
    t = ['{vol 15}', '{echo off}', '{arp 0}', '{bend 0}']
    t += ['r16', '|'] * bars_before
    t += ['@siren', 'o4', 'e4', 'g4', 'a4', '{bend -2}', 'o5', 'c4', '|']
    return t


def echo_pat(delay=21, level=7, oct_=False):
    o = ' oct' if oct_ else ''
    return ['{arp 0}', '{bend 0}', f'{{echo {delay} {level}{o}}}', '@echo', 'r64']


