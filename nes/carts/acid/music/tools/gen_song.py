# ------------------------------------------------------------------ helpers
NOTE = {'c': 0, 'd': 2, 'e': 4, 'f': 5, 'g': 7, 'a': 9, 'b': 11}
CPU = 1789773


def midi(tok):
    n = NOTE[tok[0]]
    i = 1
    if tok[i] in '#-':
        n += 1 if tok[i] == '#' else -1
        i += 1
    return 12 * (int(tok[i]) + 1) + n


def period(m):
    f = 440 * 2 ** ((m - 69) / 12)
    return round(CPU / (16 * f)) - 1


def nt(name, length):
    """'a3' -> ['o3', 'a<length>'] (octave is a separate token in the song format)."""
    return [f'o{name[-1]}', f'{name[:-1]}{length}']


def acid_bar(riff, f, slide_frames=3):
    """riff: 16 step tokens. 'a2' note, '!' accent, '~' slide into it, '.' rest, '_' tie.
    Returns pattern tokens (16 rows)."""
    out, cur, last = [], None, None
    for st in riff.split():
        if st == '.':
            out.append('r1')
            last = None
            continue
        if st == '_':
            out.append('w1')
            continue
        acc = '!' in st
        sl = '~' in st and last is not None
        name = st.replace('!', '').replace('~', '')
        m = midi(name)
        if sl:
            d = abs(period(m) - period(last))
            g = max(8, min(255, (d + slide_frames - 1) // slide_frames))
            out += [f'{{glide {g}}}'] + nt('~' + name, 1)
        else:
            inst = f'x{f}' if acc else f'a{f}'
            if inst != cur:
                out.append('@' + inst)
                cur = inst
            out += nt(name, 1)
        last = m
    assert len(riff.split()) == 16, riff
    return out


