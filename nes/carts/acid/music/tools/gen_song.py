def noise_bar(kind):
    if kind == '-':
        return ['r16', '|']
    if kind == 'q':        # intro: quiet 8th ticks
        return [('hcq1' if c == 'x' else 'w1') for c in 'x.x.x.x.x.x.x.x.'] + ['|']
    if kind == 'o':        # open off-beat hats + quiet ticks
        s = []
        for i in range(16):
            s.append('ho1' if i % 4 == 2 else ('hcq1' if i % 2 == 0 else 'w1'))
        return s + ['|']
    if kind == 'f':        # full: 16th closed + open off-beats
        s = []
        for i in range(16):
            s.append('ho1' if i % 4 == 2 else 'hc1')
        return s + ['|']
    if kind == 'm':        # metallic variation
        s = []
        for i in range(16):
            s.append('hos1' if i % 4 == 2 else ('hc1' if i % 2 else 'hcq1'))
        return s + ['|']
    if kind == 'cr':       # crash on 1, then full
        s = ['cr2']
        for i in range(2, 16):
            s.append('ho1' if i % 4 == 2 else 'hc1')
        return s + ['|']
    if kind == 'roll':     # noise snare 16ths
        return ['sn1'] * 16 + ['|']
    if kind == 'wind':
        return ['wind16', '|']
    raise ValueError(kind)


def noise_pat(kinds):
    t = []
    for k in kinds:
        t += noise_bar(k)
    return t


# ------------------------------------------------------------------ DMC
def dmc_bar(kind):
    if kind == '-':
        return ['r16', '|']
    if kind == 'k':        # kick punch on every beat
        return ['kick4'] * 4 + ['|']
    if kind == 'kc':       # kick 1 & 3, clap 2 & 4
        return ['kick4', 'clap4', 'kick4', 'clap4', '|']
    if kind == 'kcp':      # + zaps on 16ths
        return ['kick3', 'zap1', 'clap4', 'kick2', 'rim1', 'zap1', 'clap3', 'rim1', '|']
    if kind == 'kcq':      # + rims
        return ['kick3', 'rim1', 'clap2', 'rim1', 'rim1', 'kick3', 'zap1', 'clap4', '|']
    if kind == 'c8':       # build: claps in 8ths (kick on the beats)
        return ['kick2', 'clap2'] * 4 + ['|']
    if kind == 'c16':      # roll
        return ['kick1', 'clap1', 'clap1', 'clap1'] * 4 + ['|']
    if kind == 'boom':     # drop: boom then groove
        return ['boom4', 'clap4', 'kick3', 'zap1', 'clap4', '|']
    if kind == 'brk':      # build break: last clap then silence, pickup zaps
        return ['clap4', 'r8', 'zap1', 'zap1', 'zap1', 'zap1', '|']
    if kind == 'z':        # breakdown: lone zaps
        return ['r6', 'zap2', 'r6', 'rim2', '|']
    raise ValueError(kind)


def dmc_pat(kinds):
    t = []
    for k in kinds:
        t += dmc_bar(k)
    return t


