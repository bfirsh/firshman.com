def acid_bars(bars, fs, slide_frames=3, vols=None):
    """One list of tokens per bar; vols: {vol} per bar (None = unchanged)."""
    out = []
    for i, (riff, f) in enumerate(zip(bars, fs)):
        b = acid_bar(R[riff], f, slide_frames) + ['|']
        if vols and vols[i] is not None:
            b = [f'{{vol {vols[i]}}}'] + b
        out.append(b)
    return out


def acid_pat(bars, fs, slide_frames=3, vols=None):
    return [t for b in acid_bars(bars, fs, slide_frames, vols) for t in b]


def steps(spec, on, off='w1'):
    """spec: 16 chars, 'x' = hit. Emits tokens for one bar."""
    out = []
    for ch in spec:
        out.append(on if ch == 'x' else (off if ch == '.' else ch))
    return out


