def stab_bar(chord, rhythm, inst='stab'):
    n = CH[chord]
    t = ['{arp 37}']
    for c in rhythm:
        if c == 'x':
            t += [f'@{inst}'] + nt(n, 1)
        elif c == 'X':
            t += ['@stabx'] + nt(n, 1)
        else:
            t += ['w1']
    return t + ['|']


def p2_pat(chords, rhythms, inst='stab', vol=15):
    t = [f'{{vol {vol}}}', '{echo off}', '{bend 0}']
    for c, r in zip(chords, rhythms):
        if c == '-':
            t += ['{arp 0}', 'r16', '|']
        else:
            t += stab_bar(c, r, inst)
    return t


