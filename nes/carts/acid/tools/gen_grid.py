#!/usr/bin/env python3
"""The grid floor (out/gen/grid.inc, bank B23).

Nametable 0: the sky (black), a dithered glow above the horizon (line 112) and the fan of
floor lines converging on the vanishing point, brighter towards the camera. ExRAM (nametable 2)
holds three "line rows" of solid colour 1, 2 and 3: the raster kernel shows one of them on every
scanline where a cross line of the grid passes, so the cross lines are exact for any camera
position. Also: per-scanline depth table for the kernel's line test.
"""
from pathlib import Path
import numpy as np
OUT = Path(__file__).resolve().parent.parent / 'out' / 'gen' / 'grid.inc'
HZ = 112
CAMH, FOCAL = 24.0, 128.0


def enc(t):
    lo = [sum(((int(t[y, x]) & 1) << (7 - x)) for x in range(8)) for y in range(8)]
    hi = [sum(((int(t[y, x]) >> 1) << (7 - x)) for x in range(8)) for y in range(8)]
    return bytes(lo + hi)


def main():
    img = np.zeros((240, 256), int)
    for y in range(HZ + 1, 240):
        s = (y - HZ) / FOCAL
        for k in range(-10, 11):
            xi = int(np.floor(128 + k * 44 * s))
            if 0 <= xi < 256:
                img[y, xi] = 3 if y > HZ + 44 else (2 if y > HZ + 14 else 1)
    for y in range(HZ - 14, HZ + 1):
        d = HZ - y
        for x in range(256):
            if d <= 1:
                img[y, x] = 3
            elif d < 5:
                img[y, x] = 2 if (x + y) % 2 == 0 else 1
            elif d < 10:
                img[y, x] = 1 if (x + y) % 2 == 0 else 0
            else:
                img[y, x] = 1 if (x % 2 == 0 and y % 2 == 0) else 0
    tiles = {bytes(16): 0}
    nt = []
    for ty in range(30):
        for tx in range(32):
            tb = enc(img[ty * 8:ty * 8 + 8, tx * 8:tx * 8 + 8])
            if tb not in tiles:
                tiles[tb] = len(tiles)
            nt.append(tiles[tb])
    solid = []
    for c in (1, 2, 3):
        tb = enc(np.full((8, 8), c))
        if tb not in tiles:
            tiles[tb] = len(tiles)
        solid.append(tiles[tb])
    assert len(tiles) <= 256, len(tiles)
    # attributes: sky palette 1 above the glow, palette 0 for glow + floor
    attr = []
    for ay in range(8):
        for ax in range(8):
            v = 0
            for q, (qx, qy) in enumerate(((0, 0), (1, 0), (0, 1), (1, 1))):
                py = ay * 32 + qy * 16
                v |= (0 if py >= 96 else 1) << (2 * q)
            attr.append(v)
    # per scanline below the horizon: depth of the near and far edge (8.8, world units)
    za, zb = [], []
    for y in range(HZ + 1, 240):
        dy = y - HZ
        za.append(min(65535, int(CAMH * FOCAL / (dy + 0.5) * 256)))
        zb.append(min(65535, int(CAMH * FOCAL / max(dy - 0.5, 0.35) * 256)))
    L = ['; Generated by tools/gen_grid.py. Do not edit.', f'GRID_HZ = {HZ}', f'GRID_NTILES = {len(tiles)}',
         f'GRID_SOLID1 = {solid[0]}', f'GRID_SOLID2 = {solid[1]}', f'GRID_SOLID3 = {solid[2]}', '.segment "B23"', 'grid_chr:']
    for tb in sorted(tiles, key=tiles.get):
        L.append('  .byte ' + ','.join(f'${v:02X}' for v in tb))
    L.append('grid_nt:')
    for i in range(0, 960, 32):
        L.append('  .byte ' + ','.join(str(v) for v in nt[i:i + 32]))
    L.append('  .byte ' + ','.join(f'${v:02X}' for v in attr))
    for name, t in (('grid_za', za), ('grid_zb', zb)):
        L.append(f'{name}_lo:')
        L.append('  .byte ' + ','.join(str(v & 255) for v in t))
        L.append(f'{name}_hi:')
        L.append('  .byte ' + ','.join(str(v >> 8) for v in t))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(L) + '\n')
    print(f'grid: {len(tiles)} tiles')


if __name__ == '__main__':
    main()
