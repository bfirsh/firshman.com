#!/usr/bin/env python3
"""The vector scenes' backdrop (out/gen/mouth.inc, bank B24): a rectangular tunnel whose dark far
end is exactly the 128 x 96 bitmap window (columns 8-23, rows 8-19), so the polyhedra float in
its mouth. Depth bands use colours 1-3 of palette 1 (rotated to move them), black seams on the
diagonals. Output: 64 tiles for $0C00 (tiles 192-255) and the whole nametable (the window
holds the bitmap's column-major tile numbers) with attributes (palette 0 = window, 1 = rings).
"""
from pathlib import Path
import numpy as np
OUT = Path(__file__).resolve().parent.parent / 'out' / 'gen' / 'mouth.inc'


def enc(t):
    lo = [sum(((int(t[y, x]) & 1) << (7 - x)) for x in range(8)) for y in range(8)]
    hi = [sum(((int(t[y, x]) >> 1) << (7 - x)) for x in range(8)) for y in range(8)]
    return bytes(lo + hi)


def main():
    y, x = np.mgrid[0:240, 0:256]
    dx, dy = (x + 0.5 - 128) / 64, (y + 0.5 - 112) / 48
    r = np.maximum(abs(dx), abs(dy))
    d = 1.0 / np.maximum(r, 1e-3)
    b = ((d / 0.25) % 1 * 3).astype(int) + 1
    b[abs(abs(dx) - abs(dy)) < 0.012] = 0
    b[:48] = 0                     # letterbox: black above line 48 and from line 184, where the
    b[182:] = 0                    # forced blank for the CHR upload starts mid-scanline
    tiles, nt = {}, []
    for ty in range(30):
        for tx in range(32):
            if 8 <= tx < 24 and 8 <= ty < 20:
                nt.append((tx - 8) * 12 + (ty - 8))
                continue
            tb = enc(b[ty * 8:ty * 8 + 8, tx * 8:tx * 8 + 8])
            if tb not in tiles:
                tiles[tb] = 192 + len(tiles)
            nt.append(tiles[tb])
    assert len(tiles) <= 64, len(tiles)
    attr = []
    for ay in range(8):
        for ax in range(8):
            v = 0
            for q, (qx, qy) in enumerate(((0, 0), (1, 0), (0, 1), (1, 1))):
                bx, by = ax * 2 + qx, ay * 2 + qy          # 16x16 block
                inside = 4 <= bx < 12 and 4 <= by < 10
                v |= (0 if inside else 1) << (2 * q)
            attr.append(v)
    L = ['; Generated by tools/gen_mouth.py. Do not edit.', '.segment "B24"', f'MOUTH_NTILES = {len(tiles)}', 'mouth_chr:']
    for tb in sorted(tiles, key=tiles.get):
        L.append('  .byte ' + ','.join(f'${v:02X}' for v in tb))
    L.append('mouth_nt:')
    for i in range(0, 960, 32):
        L.append('  .byte ' + ','.join(str(v) for v in nt[i:i + 32]))
    L.append('  .byte ' + ','.join(f'${v:02X}' for v in attr))
    OUT.write_text('\n'.join(L) + '\n')
    print(f'mouth: {len(tiles)} tiles')


if __name__ == '__main__':
    main()
