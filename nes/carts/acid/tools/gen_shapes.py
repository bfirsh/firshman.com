#!/usr/bin/env python3
"""Ring shapes for the ball object (out/gen/shapes.inc): per shape 8 radii (0..64) then
8 heights (signed): surfaces of revolution the object morphs between."""
import math
from pathlib import Path
OUT = Path(__file__).resolve().parent.parent / 'out' / 'gen' / 'shapes.inc'
S = {}
S['sphere'] = [(60 * math.sin((k + .5) / 8 * math.pi), 60 * math.cos((k + .5) / 8 * math.pi)) for k in range(8)]
S['torus'] = [(40 + 20 * math.cos(k / 8 * 2 * math.pi), 20 * math.sin(k / 8 * 2 * math.pi)) for k in range(8)]
S['cylinder'] = [(38, -56 + 16 * k) for k in range(8)]
S['cone'] = [(6 + 8 * k, -52 + 15 * k) for k in range(8)]
S['hourglass'] = [(14 + abs(k - 3.5) * 13, -56 + 16 * k) for k in range(8)]
S['disc'] = [(8 + 8 * k, 0) for k in range(8)]
S['spindle'] = [(10 + (3.5 - abs(k - 3.5)) * 14, -60 + 17 * k) for k in range(8)]
S['point'] = [(0, 0)] * 8
S['wave'] = [(30 + 8 * k, 18 * math.sin(k * 1.2)) for k in range(8)]
L = ['; Generated by tools/gen_shapes.py. Do not edit.', 'dot_shapes:']
for i, (n, v) in enumerate(S.items()):
    L.append(f'  .byte ' + ','.join(str(int(round(r))) for r, h in v) + ', ' + ','.join(f'<({int(round(h))})' for r, h in v) + f'   ; {i} {n}')
    L.append(f'SH_{n.upper()} = {i}')
OUT.write_text('\n'.join(L) + '\n')
