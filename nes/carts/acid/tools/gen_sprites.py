#!/usr/bin/env python3
"""Sprite tiles (out/gen/sprites.inc, fixed RODATA): uploaded to $1000 by each engine.

  0      blank
  1-4    stars: 1 px, 2x2, small disc, disc with a hot centre
  5-9    shaded balls of radius 1.2 .. 3.9 px (colour 1 body, 2 rim, 3 highlight)
"""
from pathlib import Path

import numpy as np

OUT = Path(__file__).resolve().parent.parent / 'out' / 'gen' / 'sprites.inc'


def enc(t):
    lo = [sum(((int(t[y, x]) & 1) << (7 - x)) for x in range(8)) for y in range(8)]
    hi = [sum(((int(t[y, x]) >> 1) << (7 - x)) for x in range(8)) for y in range(8)]
    return lo + hi


def ball(r):
    y, x = np.mgrid[0:8, 0:8]
    dx, dy = x + 0.5 - 4, y + 0.5 - 4
    d = np.hypot(dx, dy)
    t = np.zeros((8, 8), int)
    t[d < r] = 1
    t[(d < r) & (d > r - 1.0) & (dx + dy > 0)] = 2            # dark rim, lower right
    hl = np.hypot(dx + r * 0.35, dy + r * 0.35)
    t[(d < r) & (hl < max(0.8, r * 0.38))] = 3                  # highlight, upper left
    return t


def main():
    tiles = [np.zeros((8, 8), int)]
    s = np.zeros((8, 8), int); s[3, 3] = 1; tiles.append(s)
    s = np.zeros((8, 8), int); s[3:5, 3:5] = 1; tiles.append(s)
    s = np.zeros((8, 8), int); s[2:6, 3:5] = 1; s[3:5, 2:6] = 1; tiles.append(s)
    s = np.zeros((8, 8), int); s[1:7, 3:5] = 1; s[3:5, 1:7] = 1; s[2:6, 2:6] = 1; s[3:5, 3:5] = 3; tiles.append(s)
    for r in (1.3, 1.9, 2.6, 3.3, 4.0):
        tiles.append(ball(r))
    L = ['; Generated by tools/gen_sprites.py. Do not edit.', 'spr_chr:']
    for t in tiles:
        L.append('  .byte ' + ','.join(f'${v:02X}' for v in enc(t)))
    L.append('spr_chr_end:')
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(L) + '\n')


if __name__ == '__main__':
    main()
