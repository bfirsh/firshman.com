#!/usr/bin/env python3
"""Math tables for the Acid cartridge (out/gen/tables.inc, assembled into the fixed RODATA).

  sin8        256 x signed sine, amplitude 127 (cos = sin8[i + 64])
  persp       perspective factor k(z) = 128 * D / (D + z), z = signed byte index, clamped to 255
  col_lo/hi   start of each bitmap column in the RAM buffer (column-major, 96 bytes per column)
  bit_of_x    pixel mask for x & 7
  sq_lo/hi    quarter squares floor(n*n/4), n = 0..511, for the table multiply used in interrupts
"""
import math
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'out' / 'gen' / 'tables.inc'
D = 256


def table(name, vals, L):
    L.append(f'{name}:')
    for i in range(0, len(vals), 16):
        L.append('  .byte ' + ','.join(f'${v & 255:02X}' for v in vals[i:i + 16]))


def main():
    L = ['; Generated by tools/gen_tables.py. Do not edit.']
    table('sin8', [round(127 * math.sin(2 * math.pi * i / 256)) for i in range(256)], L)
    pz = []
    for i in range(256):
        z = i - 256 if i >= 128 else i
        pz.append(min(255, round(128 * D / (D + z))))
    table('persp', pz, L)
    table('col_lo', [(0x6000 + c * 96) & 255 for c in range(16)], L)
    table('col_hi', [(0x6000 + c * 96) >> 8 for c in range(16)], L)
    table('bit_of_x', [0x80 >> (i & 7) for i in range(8)], L)
    sq = [n * n // 4 for n in range(512)]
    table('sq_lo', [v & 255 for v in sq], L)
    table('sq_hi', [v >> 8 for v in sq], L)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(L) + '\n')


if __name__ == '__main__':
    main()
