#!/usr/bin/env python3
"""The square tunnel (out/gen/tunnel.inc, bank B22).

Every pixel's depth is d = K / r with r the Chebyshev distance from the vanishing point, and
its colour index is the depth band: 1 + floor(3 * frac(d / PERIOD + p)). Three images with
p = 0, 1/9, 2/9 go into three nametables (CIRAM A, CIRAM B, ExRAM); rotating the three colours
of the palette moves the bands by 1/3. Alternating nametable and palette rotation gives nine
sub-steps per band period: smooth flight with zero CPU. Black seams run along the diagonals and
the far end is black. Attributes give four fog levels (palette 0 = far ... 3 = near).

Outputs: tun_chr (tiles, 16 bytes each; tile 0 black), tun_ntiles, tun_nt0..2 (960 bytes each),
tun_attr (64 bytes, the same for the three nametables).
"""
from pathlib import Path

import numpy as np

OUT = Path(__file__).resolve().parent.parent / 'out' / 'gen' / 'tunnel.inc'
CX, CY = 128, 120
K, PERIOD, HOLE = 1100.0, 9.0, 11


def image(p):
    y, x = np.mgrid[0:240, 0:256]
    dx, dy = x + 0.5 - CX, y + 0.5 - CY
    r = np.maximum(np.abs(dx), np.abs(dy))
    d = K / np.maximum(r, 1)
    u = (d / PERIOD + p) % 1.0
    b = (u * 3).astype(int) + 1
    b[r < HOLE] = 0
    seam = np.abs(np.abs(dx) - np.abs(dy)) < 1.0
    b[seam & (r >= HOLE)] = 0
    return b


def tile_bytes(t):
    lo = [sum(((int(t[y, x]) & 1) << (7 - x)) for x in range(8)) for y in range(8)]
    hi = [sum(((int(t[y, x]) >> 1) << (7 - x)) for x in range(8)) for y in range(8)]
    return bytes(lo + hi)


def main():
    tiles = {bytes(16): 0}
    nts = []
    for k in range(3):
        b = image(k / 9)
        nt = []
        for ty in range(30):
            for tx in range(32):
                tb = tile_bytes(b[ty * 8:ty * 8 + 8, tx * 8:tx * 8 + 8])
                if tb not in tiles:
                    tiles[tb] = len(tiles)
                nt.append(tiles[tb])
        nts.append(nt)
    assert len(tiles) <= 256, len(tiles)
    # attributes: fog by the Chebyshev distance of each 16x16 block's centre
    attr = []
    for ay in range(8):
        for ax in range(8):
            v = 0
            for q, (qx, qy) in enumerate(((0, 0), (1, 0), (0, 1), (1, 1))):
                bx, by = ax * 32 + qx * 16 + 8, ay * 32 + qy * 16 + 8
                r = max(abs(bx - CX), abs(by - CY))
                z = 0 if r < 30 else 1 if r < 56 else 2 if r < 88 else 3
                v |= z << (2 * q)
            attr.append(v)
    L = ['; Generated by tools/gen_tunnel.py. Do not edit.', '.segment "B22"']
    L.append(f'TUN_NTILES = {len(tiles)}')
    L.append('tun_chr:')
    for tb in sorted(tiles, key=tiles.get):
        L.append('  .byte ' + ','.join(f'${v:02X}' for v in tb))
    for k, nt in enumerate(nts):
        L.append(f'tun_nt{k}:')
        for i in range(0, 960, 32):
            L.append('  .byte ' + ','.join(str(v) for v in nt[i:i + 32]))
    L.append('tun_attr:')
    L.append('  .byte ' + ','.join(f'${v:02X}' for v in attr))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(L) + '\n')
    print(f'tunnel: {len(tiles)} tiles')


if __name__ == '__main__':
    main()
