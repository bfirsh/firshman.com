#!/usr/bin/env python3
"""Generate the vector engine's CHR-RAM upload code (out/gen/upload.s).

The bitmap is 16 x 12 tiles (128 x 96 px), stored column-major in PRG-RAM at $6000 (96 bytes per
tile column, so tile t = column * 12 + row lives at $6000 + 8t). A frame of the 30 fps vector
animation is uploaded in two video frames (half 0 = tiles 0-95, half 1 = tiles 96-191), each
split between the forced-blank IRQ at the bottom of the screen (IRQ_TILES) and the vblank NMI
(the rest). Only ONE bitplane is written: plane 0 and plane 1 of the same tiles are the two
buffers, and the palette decides which one is visible.

Per tile: stx $2006 / lda #lo / sta $2006 (X keeps the high byte), then 8 x (lda abs / sta $2007):
74 cycles. Banks B16-B19 = (plane 0, half 0), (plane 0, half 1), (plane 1, half 0), (plane 1, half 1);
each starts with   $A000: jmp irq_part   $A003: jmp nmi_part.
"""
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'out' / 'gen' / 'upload.s'
IRQ_TILES = int(sys.argv[1]) if len(sys.argv) > 1 else 76
HALF = 96


def chunk(L, tiles, plane):
    L.append('  bit $2002')
    hi = None
    for t in tiles:
        a = t * 16 + plane * 8
        if a >> 8 != hi:
            hi = a >> 8
            L.append(f'  ldx #${hi:02X}')
        L.append('  stx $2006')
        L.append(f'  lda #${a & 255:02X}')
        L.append('  sta $2006')
        for i in range(8):
            L.append(f'  lda ${0x6000 + t * 8 + i:04X}')
            L.append('  sta $2007')
    L.append('  rts')


def main():
    L = ['; Generated by tools/gen_upload.py. Do not edit.', f'UPL_IRQ_TILES = {IRQ_TILES}']
    for bank, (plane, half) in zip(range(16, 20), [(0, 0), (0, 1), (1, 0), (1, 1)]):
        L.append(f'.segment "B{bank}"')
        L.append(f'.scope upl{bank}')
        L.append('  jmp irq_part')
        L.append('  jmp nmi_part')
        tiles = list(range(half * HALF, (half + 1) * HALF))
        L.append('irq_part:')
        chunk(L, tiles[:IRQ_TILES], plane)
        L.append('nmi_part:')
        chunk(L, tiles[IRQ_TILES:], plane)
        L.append('.endscope')
    # B20: unrolled clears, one routine per bitmap column (enter at row y, runs to row 95)
    L.append('.segment "B20"')
    L.append('clr_entry_lo:')
    L.append('  .byte ' + ', '.join(f'<clr_col{c}' for c in range(16)))
    L.append('clr_entry_hi:')
    L.append('  .byte ' + ', '.join(f'>clr_col{c}' for c in range(16)))
    for c in range(16):
        L.append(f'clr_col{c}:')
        for y in range(96):
            L.append(f'  sta ${0x6000 + c * 96 + y:04X}')
        L.append('  rts')
    # B21: star rays: 64 rays x 64 depth steps, signed screen offsets ($80 = off screen)
    import math, random
    rnd = random.Random(1)
    rays = []
    for r in range(64):
        ang = (r + rnd.random() * 0.8) * 2 * math.pi / 64
        rad = 0.25 + 0.75 * rnd.random() ** 0.7
        rays.append((math.cos(ang) * rad, math.sin(ang) * rad))
    L.append('.segment "B21"')
    for comp, lim in ((0, 124), (1, 116)):
        L.append(f'star_off{"xy"[comp]}:')
        for cx, cy in rays:
            row = []
            for zi in range(64):
                z = 1.0 - zi / 64 * 0.94          # depth 1.0 (far) .. 0.06 (near)
                v = (cx, cy)[comp] * 22 / z
                row.append(0x80 if abs(v) > lim else int(round(v)) & 255)
            L.append('  .byte ' + ','.join(f'${b:02X}' for b in row))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(L) + '\n')


if __name__ == '__main__':
    main()
