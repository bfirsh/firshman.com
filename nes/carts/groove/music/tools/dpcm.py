#!/usr/bin/env python3
"""Synthesise the DPCM drum samples (no third-party audio) and encode them for the NES DMC.

usage: dpcm.py [-o dpcm.inc] [--preview DIR]

Every sample starts and ends at the DMC rest level REST (music_init writes it to $4011), so the
DMC output always comes back to the same level and the triangle/noise loudness stays constant.
Samples are padded to 64-byte boundaries; the DPCM segment must start on one.
"""
import math
import random
import sys
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RATES = [4181.71, 4709.93, 5264.04, 5593.04, 6257.95, 7046.35, 7919.35, 8363.42,
         9419.86, 11186.1, 12604.0, 13982.6, 16884.6, 21306.8, 24858.0, 33143.9]
REST = 36


def kick(sr):
    """Round, punchy funk kick: a short pitch sweep into a ~55 Hz body, a soft beater click."""
    n = int(0.16 * sr)
    out, ph = [], 0.0
    for i in range(n):
        t = i / sr
        f = 52 + 110 * math.exp(-t / 0.022)
        ph += 2 * math.pi * f / sr
        a = min(1, t / 0.0015) * math.exp(-t / 0.07)
        click = 0.35 * math.exp(-t / 0.0025)
        out.append(a * math.sin(ph) + click)
    return out


def snare(sr, seed=3):
    """Tight funk snare: a 190 Hz drum body with a bright, quickly closing noise burst."""
    rnd = random.Random(seed)
    n = int(0.15 * sr)
    out, ph, lp, hp = [], 0.0, 0.0, 0.0
    for i in range(n):
        t = i / sr
        f = 205 - 30 * min(1, t / 0.02)
        ph += 2 * math.pi * f / sr
        body = 0.7 * math.sin(ph) * math.exp(-t / 0.03)
        w = rnd.uniform(-1, 1)
        lp += 0.6 * (w - lp)
        noise = 0.85 * lp * math.exp(-t / 0.045)
        out.append((body + noise) * min(1, t / 0.001))
    return out


def rim(sr, seed=5):
    """Cross-stick / rimshot: a woody knock (two damped partials) and a click."""
    rnd = random.Random(seed)
    n = int(0.06 * sr)
    out, p1, p2 = [], 0.0, 0.0
    for i in range(n):
        t = i / sr
        p1 += 2 * math.pi * 520 / sr
        p2 += 2 * math.pi * 1240 / sr
        knock = 0.7 * math.sin(p1) * math.exp(-t / 0.012) + 0.45 * math.sin(p2) * math.exp(-t / 0.006)
        click = rnd.uniform(-1, 1) * 0.5 * math.exp(-t / 0.0015)
        out.append(knock + click)
    return out


def clap(sr, seed=9):
    """Snare layered with a hand clap: three quick noise bursts, then a short room tail."""
    rnd = random.Random(seed)
    sn = snare(sr, seed=4)
    n = int(0.2 * sr)
    out, lp, bp = [], 0.0, 0.0
    for i in range(n):
        t = i / sr
        w = rnd.uniform(-1, 1)
        lp += 0.5 * (w - lp)
        bp = w - lp                      # crude high-pass: claps are bright
        env = 0.0
        for k, at in enumerate((0.0, 0.011, 0.022)):
            if t >= at:
                env = max(env, (0.8 - 0.1 * k) * math.exp(-(t - at) / 0.004))
        if t >= 0.03:
            env = max(env, 0.55 * math.exp(-(t - 0.03) / 0.05))
        s = 0.6 * bp * env + (0.6 * sn[i] if i < len(sn) else 0)
        out.append(s)
    return out


def encode(sig, amp):
    """Greedy delta-modulation encode of sig (floats about 0) scaled by amp DMC units.
    Returns (bytes, decoded levels). Length is 16n+1 bytes, ending at REST."""
    level, bits, dec = REST, [], []
    target = [min(124, max(4, REST + amp * s)) for s in sig]   # never hit the DMC's 0/127 clamps
    for y in target:
        b = 1 if y > level else 0
        if b and level <= 125:
            level += 2
        elif not b and level >= 2:
            level -= 2
        bits.append(b)
        dec.append(level)
    # walk back to REST, then alternate (holds level)
    while level != REST:
        b = 1 if level < REST else 0
        level += 2 if b else -2
        bits.append(b)
        dec.append(level)
    nbytes = (len(bits) + 7) // 8
    nbytes = ((nbytes - 1 + 15) // 16) * 16 + 1
    alt = 0
    while len(bits) < nbytes * 8:
        bits.append(alt)
        level += 2 if alt else -2
        dec.append(level)
        alt ^= 1
    # the last two bits must leave the level at REST: an even number of alternating bits does
    out = bytearray()
    for i in range(nbytes):
        v = 0
        for k in range(8):
            v |= bits[i * 8 + k] << k   # DMC plays bit 0 first
        out.append(v)
    return bytes(out), dec, level


SAMPLES = [  # name, synth, rate index, amplitude in DMC units
    ('kick', kick, 14, 36),
    ('snare', snare, 14, 26),
    ('rim', rim, 15, 22),
    ('clap', clap, 14, 26),
]


def main():
    args = sys.argv[1:]
    out = ROOT / 'dpcm.inc'
    preview = None
    if '-o' in args:
        out = Path(args[args.index('-o') + 1])
    if '--preview' in args:
        preview = Path(args[args.index('--preview') + 1])
    L = ['; Generated by nes/music/tools/dpcm.py (synthesised drums). Do not edit.',
         f'; DMC rest level: {REST}. Each sample starts on a 64-byte boundary.', '']
    total = 0
    for name, fn, rate, amp in SAMPLES:
        sr = RATES[rate]
        data, dec, end = encode(fn(sr), amp)
        assert end == REST, (name, end)
        assert len(data) % 16 == 1
        L.append(f'dpcm_{name}:')
        for i in range(0, len(data), 16):
            L.append('  .byte ' + ','.join(f'${b:02X}' for b in data[i:i + 16]))
        L.append(f'dpcm_{name}_end:')
        pad = (-len(data)) % 64
        if pad:
            L.append(f'  .res {pad}, $00')
        total += len(data) + pad
        print(f'  {name}: {len(data)} bytes at rate {rate} ({sr:.0f} Hz), {len(data) * 8 / sr * 1000:.0f} ms, '
              f'level range {min(dec)}..{max(dec)}')
        if preview:
            preview.mkdir(parents=True, exist_ok=True)
            with wave.open(str(preview / f'dpcm_{name}.wav'), 'wb') as w:
                w.setnchannels(1); w.setsampwidth(2); w.setframerate(int(sr))
                w.writeframes(b''.join(int((d - REST) * 250).to_bytes(2, 'little', signed=True) for d in dec))
    L.append(f'DPCM_REST = {REST}')
    out.write_text('\n'.join(L) + '\n')
    print(f'{out}: {total} bytes of DPCM (limit 4096)')
    assert total <= 4096


if __name__ == '__main__':
    main()
