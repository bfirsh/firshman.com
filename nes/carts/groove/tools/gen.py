def scene_shout():
    """SHOUT: concentric diamonds in hot colours."""
    phase = np.zeros((30, 32))
    colsel = np.zeros((30, 32), int)
    for ty in range(30):
        for tx in range(32):
            x, y = tx * 8 + 4 - 128, ty * 8 + 4 - 116
            d = abs(x) + abs(y)
            phase[ty, tx] = -d / 48.0
            colsel[ty, tx] = int((x > 0) != (y > 0))
    attr = np.zeros((15, 16), int)
