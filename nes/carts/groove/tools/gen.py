def waves():
    """8 sine tables of 512 bytes (amplitudes 0,1,2,3,5,8,12,20 px), period 64 lines."""
    amps = [0, 1, 2, 3, 5, 8, 12, 20]
    b = bytearray()
    for a in amps:
        for i in range(512):
            b.append(int(round(a * math.sin(2 * math.pi * i / 64))) & 255)
    (OUT / 'waves.bin').write_bytes(bytes(b))
    INC.append('; waves.bin: 8 tables x 512 at WAVES (amplitudes ' + ','.join(map(str, amps)) + '), period 64')
    inc_bytes('sin8', [int(round(127 * math.sin(2 * math.pi * i / 256))) for i in range(256)])


