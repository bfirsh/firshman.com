#!/usr/bin/env python3
"""Groove: procedural asset generator. Everything is drawn here from geometry (no source images).

Writes into out/gen/:
  chr.bin         256 KB CHR-ROM (1 KB banks, see the CHR map below)
  waves.bin       4 KB of sine tables for the raster kernel (copied to PRG-RAM $7000 at reset)
  <scene>_nt.bin  1024-byte nametables (+ attributes), <scene>_ex.bin ExRAM images
  assets.inc      constants, palettes, metasprites
  preview/*.png   what each scene's nametable looks like (for checking the design)

CHR map (1 KB bank numbers):
  4-7      sprites (8x8, pattern table $1000)
  8-11     stripes scene tiles (all four BG slots)
  32-63    LUT family A: halftone dots, 32 phases, two colours (tiles 0-31 colour 1, 32-63 colour 2)
  64-95    LUT family B: line screen (moire)
  96-127   LUT family C: diamonds
  128+     extended-attribute images, 4 KB aligned (ExRAM bank field = 4 KB index)
LUT families: bank k, tile j shows phase (j + k) mod 32, so writing bank (base + t) to $5120
advances every tile's phase by t: a nametable of phases becomes a moving field, at no CPU cost.
Each of the four BG slots can hold a different bank, so the nametable can also pick, per tile,
which phase offset (or family) it animates with. Tiles 31 and 63 are blank in every bank.
"""
import math
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'out' / 'gen'
PREV = OUT / 'preview'
sys.path.insert(0, str(ROOT.parent.parent / 'tools'))
import nespal  # noqa: E402  (JSNES palette: the colours the player really shows)

OUT.mkdir(parents=True, exist_ok=True)
PREV.mkdir(parents=True, exist_ok=True)
CHR = bytearray(256 * 1024)
INC = ['; Generated by tools/gen.py. Do not edit.', '']

# named NES colours (JSNES palette)
C = dict(paper=0x10, black=0x0F, red=0x16, amber=0x27, navy=0x0C, teal=0x1C, cream=0x37, coral=0x26,
         rust=0x17, brown=0x07, white=0x30, grey=0x2D, dgrey=0x00, cyan=0x2C, cobalt=0x11, ultra=0x01,
         yellow=0x28, maroon=0x06, crimson=0x15, peach=0x36, pale=0x38, olive=0x18, sky=0x21, pink=0x35)


def tile_bytes(px):
    """8x8 array of 0..3 -> 16 bytes of NES 2bpp."""
    px = np.asarray(px, dtype=np.uint8)
    out = bytearray(16)
    for y in range(8):
        lo = hi = 0
        for x in range(8):
            v = int(px[y, x])
            lo |= (v & 1) << (7 - x)
            hi |= ((v >> 1) & 1) << (7 - x)
        out[y] = lo
        out[8 + y] = hi
    return bytes(out)


def put_tile(bank1k, idx, px):
    o = bank1k * 1024 + idx * 16
    CHR[o:o + 16] = tile_bytes(px)


def put_tile4k(bank4k, idx, px):
    o = bank4k * 4096 + idx * 16
    CHR[o:o + 16] = tile_bytes(px)


def preview(name, img_idx, pal_rgb):
    """img_idx: HxW NES colour indices."""
    rgb = nespal.RGB[np.asarray(img_idx)].astype(np.uint8)
    Image.fromarray(rgb).resize((rgb.shape[1] * 2, rgb.shape[0] * 2), Image.NEAREST).save(PREV / f'{name}.png')


def inc_bytes(name, vals):
    INC.append(f'{name}:')
    vals = list(vals)
    for i in range(0, len(vals), 16):
        INC.append('  .byte ' + ','.join(f'${v & 255:02X}' for v in vals[i:i + 16]))


def inc_const(name, v):
    INC.append(f'{name} = {v}')


# =========================================================================== geometry helpers
YY, XX = np.mgrid[0:240, 0:256].astype(np.float64) + 0.5


def disc(cx, cy, r, x=XX, y=YY):
    return (x - cx) ** 2 + (y - cy) ** 2 <= r * r


def ring(cx, cy, r0, r1, x=XX, y=YY):
    d2 = (x - cx) ** 2 + (y - cy) ** 2
    return (d2 >= r0 * r0) & (d2 <= r1 * r1)


def rect(x0, y0, x1, y1, x=XX, y=YY):
    return (x >= x0) & (x < x1) & (y >= y0) & (y < y1)


def halftone(mask_fn, x0, y0, x1, y1, pitch, rfn, x=XX, y=YY):
    """Dots on a grid inside a box; rfn(cx, cy) -> radius."""
    out = np.zeros(x.shape, bool)
    for gy in np.arange(y0 + pitch / 2, y1, pitch):
        for gx in np.arange(x0 + pitch / 2, x1, pitch):
            r = rfn(gx, gy)
            if r > 0.3:
                out |= disc(gx, gy, r, x, y)
    return out


# =========================================================================== ext-attr images
def ext_image(name, img, pals, bg, bank4k_first, nbanks=4):
    """img: 240x256 NES colour indices. pals: 4 lists of 3 colours; bg = backdrop colour.
    Each 8x8 tile picks the palette that represents its colours best (exact when possible);
    tiles are deduplicated and packed into 4 KB banks. Returns (nt bytes, ex bytes, banks used)."""
    pal_sets = [[bg] + list(p) for p in pals]
    lab = nespal.lab(nespal.RGB)
    tiles = {}
    order = []
    nt = bytearray(1024)
    ex = bytearray(1024)
    shown = np.zeros_like(img)
    bad = 0
    for ty in range(30):
        for tx in range(32):
            blk = img[ty * 8:ty * 8 + 8, tx * 8:tx * 8 + 8]
            cols = set(np.unique(blk).tolist())
            best, bp, bmap = None, 0, None
            for pi, ps in enumerate(pal_sets):
                # map each colour to the nearest in the palette
                m = {c: min(range(4), key=lambda k: np.linalg.norm(lab[c] - lab[ps[k]])) for c in cols}
                err = sum(np.linalg.norm(lab[c] - lab[ps[m[c]]]) * (blk == c).sum() for c in cols)
                if best is None or err < best - 1e-9:
                    best, bp, bmap = err, pi, m
            if best > 0:
                bad += 1
            px = np.vectorize(lambda c: bmap[c])(blk).astype(np.uint8)
            shown[ty * 8:ty * 8 + 8, tx * 8:tx * 8 + 8] = np.vectorize(lambda v: pal_sets[bp][v])(px)
            key = tile_bytes(px)
            if key not in tiles:
                tiles[key] = len(order)
                order.append(px)
            ti = tiles[key]
            nt[ty * 32 + tx] = ti & 255
            ex[ty * 32 + tx] = ((bank4k_first + ti // 256) & 63) | (bp << 6)
    assert len(order) <= 256 * nbanks, (name, len(order))
    for i, px in enumerate(order):
        put_tile4k(bank4k_first + i // 256, i % 256, px)
    (OUT / f'{name}_nt.bin').write_bytes(bytes(nt))
    (OUT / f'{name}_ex.bin').write_bytes(bytes(ex))
    preview(name, shown, None)
    print(f'  {name}: {len(order)} unique tiles in {(len(order) + 255) // 256} x 4 KB, {bad} tiles approximated')
    return nt, ex


def pal_bytes(bgpals, sprpals, backdrop):
    out = []
    for p in bgpals:
        out += [backdrop] + list(p)
    for p in sprpals:
        out += [backdrop] + list(p)
    return out


# =========================================================================== sprites
SPR_TILES = []        # 8x8 sprite tiles
SPR_INDEX = {}


def spr_tile(px16):
    key = px16.tobytes()
    if key not in SPR_INDEX:
        SPR_INDEX[key] = len(SPR_TILES)
        SPR_TILES.append(px16)
    return SPR_INDEX[key]


def spr_byte(n):
    """8x16 sprite number -> OAM tile byte (bit 0 selects the pattern table)."""
    return 2 * n if n < 128 else 2 * (n - 128) + 1


def metasprite(name, px, ox=None, oy=None):
    """px: HxW 0..3 image; cut into 8x8 cells, empty cells skipped. Offsets relative to (ox, oy)
    (default: the centre). Emits name: count, (dy, tile, attr, dx)*."""
    h, w = px.shape
    H = (h + 7) // 8 * 8
    W = (w + 7) // 8 * 8
    big = np.zeros((H, W), np.uint8)
    big[:h, :w] = px
    ox = W // 2 if ox is None else ox
    oy = H // 2 if oy is None else oy
    ents = []
    rows = []
    for cy in range(0, H, 8):
        run = []
        for cx in range(0, W, 8):
            cell = big[cy:cy + 8, cx:cx + 8]
            if not cell.any():
                continue
            ents.append((cy - oy, spr_tile(cell), 0, cx - ox))
            run.append((cx - ox, ents[-1][1]))
        if run:   # a row: the cells must be contiguous for the grid format
            xs = [r[0] for r in run]
            assert xs == list(range(xs[0], xs[0] + 8 * len(xs), 8)), name
            rows.append((cy - oy, xs[0], [r[1] for r in run]))
    # grid format: rows, (dy, dx0, count, tiles...)*
    vals = [len(rows)]
    for dy, dx, ts in rows:
        vals += [dy & 255, dx & 255, len(ts)] + ts
    inc_bytes(name, vals)
    per_line = max(sum(1 for e in ents if e[0] <= yy < e[0] + 8) for yy in range(-H, H))
    return len(ents), per_line


def disc_px(w, h, c=1, c2=None, ring_w=0, hi=None):
    y, x = np.mgrid[0:h, 0:w].astype(float) + 0.5
    rx, ry = w / 2, h / 2
    d = ((x - rx) / rx) ** 2 + ((y - ry) / ry) ** 2
    px = np.zeros((h, w), np.uint8)
    px[d <= 1] = c
    if c2 is not None and ring_w:
        rr = 1 - ring_w / min(rx, ry)
        px[(d <= 1) & (d > rr * rr)] = c2
    if hi is not None:          # a highlight crescent
        hx, hy, hr, hc = hi
        dh = ((x - hx) / hr) ** 2 + ((y - hy) / hr) ** 2
        px[(d <= 1) & (dh <= 1)] = hc
    return px


def build_sprites():
    print('sprites')
    INC.append('; ---- metasprites (8x8 sprites), grid format: rows, (dy, dx0, count, tiles...)*')
    res = {}
    res['ball32'] = metasprite('ms_ball32', disc_px(32, 32, 1, 2, 3))
    res['ball_sq'] = metasprite('ms_ball_sq', disc_px(40, 24, 1, 2, 3), oy=8)
    res['ball_st'] = metasprite('ms_ball_st', disc_px(24, 40, 1, 2, 3), oy=24)
    res['disc48'] = metasprite('ms_disc48', disc_px(48, 48, 1, 3, 4))
    res['disc48b'] = metasprite('ms_disc48b', disc_px(48, 48, 2, 3, 4))
    res['disc24'] = metasprite('ms_disc24', disc_px(24, 24, 1))
    res['disc16'] = metasprite('ms_disc16', disc_px(16, 16, 1))
    res['dot8'] = metasprite('ms_dot8', disc_px(8, 8, 1), oy=4)
    res['dot8b'] = metasprite('ms_dot8b', disc_px(8, 8, 2), oy=4)
    res['dot6'] = metasprite('ms_dot6', np.pad(disc_px(6, 6, 3), 1), oy=4)
    # a short vertical bar (bar-graph pieces) and a long one
    bar = np.zeros((16, 8), np.uint8)
    bar[:, 2:6] = 1
    res['bar16'] = metasprite('ms_bar16', bar, ox=4, oy=0)
    for k, (n, pl) in res.items():
        print(f'  {k}: {n} sprites, {pl} per line')
    # the sheet: 8x8 sprite tiles in CHR banks 4-7 (pattern table $1000)
    assert len(SPR_TILES) <= 256
    for n, px in enumerate(SPR_TILES):
        put_tile(4 + n // 64, n % 64, px)
    print(f'  {len(SPR_TILES)} sprite tiles')


# =========================================================================== LUT families
def lut_family(base, shape):
    """shape(phase 0..1, colour) -> 8x8 px. Bank base+k, tile j: phase (j + k) mod 32, colour
    1 for j < 32, 2 for j >= 32."""
    for k in range(32):
        for j in range(64):
            p = ((j + k) % 32) / 32
            if j % 32 == 31:     # tiles 31 and 63: blank in every bank (borders, gaps)
                put_tile(base + k, j, np.zeros((8, 8), np.uint8))
            else:
                put_tile(base + k, j, shape(p, 1 if j < 32 else 2))


def shape_dot(p, col):
    # radius: a pulse that swells and shrinks once per cycle (rings of big dots between gaps)
    s = max(0.0, math.cos(2 * math.pi * p)) ** 0.9
    r = 0.35 + 5.0 * s
    y, x = np.mgrid[0:8, 0:8] + 0.5
    px = np.zeros((8, 8), np.uint8)
    px[(x - 4) ** 2 + (y - 4) ** 2 <= r * r] = col
    if r > 4.4:   # the biggest dots get a core in colour 3
        px[(x - 4) ** 2 + (y - 4) ** 2 <= (r - 3.2) ** 2] = 3
    return px


def shape_lines(p, col):
    # line screen: one horizontal line per tile whose thickness follows the phase
    t = max(0.0, math.cos(2 * math.pi * p)) ** 0.8
    th = t * 7.0
    px = np.zeros((8, 8), np.uint8)
    for y in range(8):
        if abs(y + 0.5 - 4) < th / 2:
            px[y, :] = col
    if th > 5.5:
        px[3:5, :] = 3
    return px


def shape_diamond(p, col):
    s = max(0.0, math.cos(2 * math.pi * p))
    r = 0.4 + 5.2 * s
    y, x = np.mgrid[0:8, 0:8] + 0.5
    d = np.abs(x - 4) + np.abs(y - 4)
    px = np.zeros((8, 8), np.uint8)
    px[d <= r] = col
    if r > 4.6:
        px[d <= r - 3.4] = 3
    return px


# =========================================================================== phase-map scenes
def phase_scene(name, phase, colsel, attr, blank_tile, page_pals, slot=None):
    """phase: 30x32 floats (cycles), colsel: 30x32 0/1 (LUT colour), attr: 15x16 palette numbers,
    slot: 30x32 0..3 (which BG slot = which phase offset / family the tile animates with).
    Rows 0-2 and 27-29 are blank. Writes the nametable."""
    nt = bytearray(1024)
    for ty in range(30):
        for tx in range(32):
            if ty < 3 or ty >= 27:
                nt[ty * 32 + tx] = blank_tile
            else:
                j = int(round(phase[ty, tx] * 32)) % 32
                if j == 31:
                    j = 30 if (phase[ty, tx] * 32) % 32 < 31 else 0
                sl = 0 if slot is None else int(slot[ty, tx])
                nt[ty * 32 + tx] = 64 * sl + j + 32 * int(colsel[ty, tx])
    for ay in range(8):
        for ax in range(8):
            v = 0
            for q, (dy, dx) in enumerate(((0, 0), (0, 1), (1, 0), (1, 1))):
                yy, xx = ay * 2 + dy, ax * 2 + dx
                p = attr[yy, xx] if yy < 15 else 0
                v |= (p & 3) << (2 * q)
            nt[960 + ay * 8 + ax] = v
    (OUT / f'{name}_nt.bin').write_bytes(bytes(nt))
    return nt


def render_normal(nt, tiles_fn, pals, backdrop):
    """Preview a normal-mode nametable: tiles_fn(tile) -> 8x8 px."""
    img = np.zeros((240, 256), np.uint8)
    for ty in range(30):
        for tx in range(32):
            t = nt[ty * 32 + tx]
            a = nt[960 + (ty // 4) * 8 + tx // 4]
            sh = ((ty // 2) % 2) * 4 + ((tx // 2) % 2) * 2
            pn = (a >> sh) & 3
            px = tiles_fn(t)
            cols = [backdrop] + list(pals[pn])
            img[ty * 8:ty * 8 + 8, tx * 8:tx * 8 + 8] = np.vectorize(lambda v: cols[v])(px)
    return img


# =========================================================================== scenes
def wordmark(x0, y0, h=12, sw=2.2):
    """'GROOVE' in a geometric face built from rings and bars (the cartridge's one word).
    Returns a mask."""
    m = np.zeros(XX.shape, bool)
    r = h / 2
    cy = y0 + r
    x = x0

    def ringm(cx):
        d = np.hypot(XX - cx, YY - cy)
        return (d <= r) & (d >= r - sw)
    # G: a ring open at the upper right, with a bar into the middle
    cx = x + r
    g = ringm(cx) & ~((XX > cx + 1) & (YY < cy - 0.5) & (YY > cy - r))
    g |= rect(cx, cy - sw / 2, cx + r, cy + sw / 2)
    m |= g
    x += h + 3
    # R: stem, a bowl on the top half, a leg
    r1 = h * 0.29
    bx = x + 5
    m |= rect(x, y0, x + sw, y0 + h)
    m |= rect(x, y0, bx, y0 + sw) | rect(x, y0 + 2 * r1 - sw, bx, y0 + 2 * r1)
    d = np.hypot(XX - bx, YY - (y0 + r1))
    m |= (d <= r1) & (d >= r1 - sw) & (XX >= bx)
    t = (YY - (y0 + 2 * r1)) / (h - 2 * r1)
    m |= (np.abs(XX - (bx - 1 + t * (r1 + 2))) < sw * 0.7) & (t >= 0) & (t <= 1)
    x += int(bx - x + r1) + 4
    # O, O
    for _ in range(2):
        m |= ringm(x + r)
        x += h + 3
    # V
    t = (YY - y0) / h
    for side in (-1, 1):
        cxv = x + r + side * r * (1 - t)
        m |= (np.abs(XX - cxv) < sw * 0.75) & (YY >= y0) & (YY < y0 + h)
    x += h + 3
    # E
    m |= rect(x, y0, x + sw, y0 + h)
    for yy in (y0, cy - sw / 2, y0 + h - sw):
        m |= rect(x, yy, x + h * 0.6, yy + sw)
    return m


def scene_disc():
    """DISC: the opening poster. Paper field, a big black disc eclipsed by a vermilion one, an amber
    moon, a navy floor line, a teal halftone corner and three black rhythm bars."""
    img = np.full((240, 256), C['paper'], np.uint8)
    ht = halftone(None, 160, 24, 248, 112, 8, lambda gx, gy: 3.6 * max(0, 1 - math.hypot(gx - 248, gy - 24) / 110) ** 0.7)
    img[ht] = C['teal']
    img[disc(104, 120, 64)] = C['black']
    img[disc(170, 142, 40)] = C['red']
    img[disc(170, 142, 40) & disc(104, 120, 64)] = C['maroon']
    img[ring(170, 142, 40, 44) & ~disc(104, 120, 64)] = C['amber']
    img[disc(146, 66, 15)] = C['amber']
    img[rect(16, 186, 240, 194)] = C['navy']
    for bx in (18, 26, 34):
        img[rect(bx, 40, bx + 3, 186)] = C['black']
    img[rect(224, 120, 240, 186)] = C['cream']
    img[rect(224, 120, 240, 186) & (((XX.astype(int) + YY.astype(int)) // 4) % 2 == 0)] = C['coral']
    img[wordmark(46, 40, h=13)] = C['black']
    img[:24] = C['paper']
    img[216:] = C['paper']
    pals = [[C['black'], C['red'], C['amber']], [C['navy'], C['teal'], C['cream']],
            [C['black'], C['maroon'], C['red']], [C['cream'], C['coral'], C['amber']]]
    ext_image('disc', img, pals, C['paper'], 32)
    spr = [[C['amber'], C['brown'], C['cream']], [C['black'], C['red'], C['white']],
           [C['navy'], C['teal'], C['cream']], [C['red'], C['amber'], C['cream']]]
    inc_bytes('pal_disc', pal_bytes(pals, spr, C['paper']))


def scene_halftone():
    """HALF: concentric halftone rings around an off-centre point; colour 1 amber / colour 2 coral."""
    phase = np.zeros((30, 32))
    colsel = np.zeros((30, 32), int)
    for ty in range(30):
        for tx in range(32):
            x, y = tx * 8 + 4, ty * 8 + 4
            d = math.hypot(x - 112, y - 108)
            phase[ty, tx] = -d / 56.0
            colsel[ty, tx] = 1 if (x - 112) * 0.5 + (y - 108) > 0 else 0
    attr = np.zeros((15, 16), int)
    for ay in range(15):
        for ax in range(16):
            attr[ay, ax] = 1 if ax >= 8 else 0
    pals = [[C['amber'], C['cream'], C['red']], [C['coral'], C['cream'], C['red']],
            [C['teal'], C['cream'], C['cyan']], [C['amber'], C['cream'], C['red']]]
    nt = phase_scene('half', phase, colsel, attr, 31, pals, slot=np.fromfunction(lambda ty, tx: (ty // 2) % 2, (30, 32), dtype=int))
    img = render_normal(nt, lambda t: shape_dot(((t % 32)) / 32, 1 + (t % 64) // 32) if t % 32 != 31 else np.zeros((8, 8), int), pals, C['navy'])
    preview('half', img, None)
    spr = [[C['cream'], C['pale'], C['white']], [C['black'], C['navy'], C['white']],
           [C['red'], C['amber'], C['cream']], [C['teal'], C['cyan'], C['white']]]
    inc_bytes('pal_half', pal_bytes(pals, spr, C['navy']))


def scene_spiral():
    """SPIRAL: a four-armed log spiral of halftone dots: advancing the phase turns it."""
    phase = np.zeros((30, 32))
    colsel = np.zeros((30, 32), int)
    for ty in range(30):
        for tx in range(32):
            x, y = tx * 8 + 4 - 128, ty * 8 + 4 - 116
            a = math.atan2(y, x)
            d = math.hypot(x, y) + 1
            phase[ty, tx] = 2 * a / (2 * math.pi) + math.log(d) * 1.4
            colsel[ty, tx] = int(((a / (2 * math.pi)) * 2 + math.log(d) * 0.7) % 1 > 0.5)
    attr = np.zeros((15, 16), int)
    for ay in range(15):
        for ax in range(16):
            r = math.hypot(ax * 16 + 8 - 128, ay * 16 + 8 - 116)
            attr[ay, ax] = 0 if r < 64 else (1 if r < 112 else 2)
    pals = [[C['cream'], C['amber'], C['white']], [C['teal'], C['cream'], C['cyan']],
            [C['cobalt'], C['teal'], C['sky']], [C['cream'], C['amber'], C['white']]]
    nt = phase_scene('spiral', phase, colsel, attr, 31, pals)
    img = render_normal(nt, lambda t: shape_dot(((t % 32)) / 32, 1 + (t % 64) // 32) if t % 32 != 31 else np.zeros((8, 8), int), pals, C['navy'])
    preview('spiral', img, None)
    spr = [[C['red'], C['amber'], C['cream']], [C['coral'], C['peach'], C['white']],
           [C['crimson'], C['coral'], C['peach']], [C['black'], C['navy'], C['white']]]
    inc_bytes('pal_spiral', pal_bytes(pals, spr, C['navy']))


def scene_moire():
    """MOIRE: a line screen modulated by two interfering ring systems (d1 + d2): ellipses."""
    phase = np.zeros((30, 32))
    colsel = np.zeros((30, 32), int)
    for ty in range(30):
        for tx in range(32):
            x, y = tx * 8 + 4, ty * 8 + 4
            d1 = math.hypot(x - 84, y - 112)
            d2 = math.hypot(x - 172, y - 112)
            phase[ty, tx] = (d1 + d2) / 40.0
            colsel[ty, tx] = int(((d1 - d2) / 40.0) % 1 > 0.5)
    attr = np.zeros((15, 16), int)
    for ay in range(15):
        for ax in range(16):
            attr[ay, ax] = (ay // 2) % 2 if 2 <= ay <= 12 else 2
    pals = [[C['cyan'], C['teal'], C['white']], [C['teal'], C['cyan'], C['cream']],
            [C['cobalt'], C['teal'], C['cyan']], [C['cyan'], C['teal'], C['white']]]
    nt = phase_scene('moire', phase, colsel, attr, 31, pals)
