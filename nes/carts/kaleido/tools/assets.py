#!/usr/bin/env python3
"""Kaleido asset pipeline: renders every picture, packs the CHR-ROM and writes the PRG data.

usage: assets.py [--preview DIR]
Writes ../out/gen/chr.bin (256 KB), ../out/gen/*.bin data and ../out/gen/assets.inc.

CHR layout (4 KB banks of 256 tiles; the MMC5 picks one per background tile from ExRAM):
  0 .. JB-1       Julia zoom frames, tile indices 64..255 (packed: every screen position owns an
                  index, and its tiles over the 12 frames sit in that index's slot of banks 0..)
  KAL .. KAL+15   kaleidoscope, one full bank per frame (the 128x128 cell)
  ROSE .. ROSE+3  rose window (index = position & 255, bank = ROSE + position >> 8)
  TUN .. TUN+3    rose tunnel (same layout)
  BLANK           an empty bank
  SPR             sprites: the first 1 KB of bank 0 (indices 0..63, unused by the Julia)
"""
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import nes
import julia
import kaleido
import rose
import tunnel
import sprites

OUT = HERE.parent / 'out' / 'gen'

JB_MAX = 35
KAL = 35
ROSE = 51
TUN = 55
TUN2 = 59
BLANK = 63
SPR = 0             # sprites: indices 0..63 of bank 0 (the Julia uses 64..255)


def seq_layout(img, base):
    """Image -> CHR slots and ExRAM bank bits, index = position & 255."""
    tiles = nes.tiles_of(img)
    slots = {}
    for p, t in enumerate(tiles):
        slots[(base + (p >> 8), p & 255)] = t
    return slots


def main():
    prev = None
    if '--preview' in sys.argv:
        prev = Path(sys.argv[sys.argv.index('--preview') + 1])
        prev.mkdir(parents=True, exist_ok=True)
    OUT.mkdir(parents=True, exist_ok=True)
    chr_ = nes.CHR(64)
    files = {}

    # ---- Julia zoom
    fr = julia.frames()
    nt_j, ex_j, slots, jb = julia.pack(fr, maxbanks=JB_MAX)
    for (b, i), t in slots.items():
        chr_.put(b, i, t, 'julia')
    print(f'julia: {len(fr)} frames, {len(slots)} tiles in {jb} banks')
    files['nt_julia'] = bytes(nt_j.astype(np.uint8)) + bytes(64)
    files['ex_julia'] = b''.join(bytes(e) + bytes(64) for e in ex_j)       # 1 KB stride

    # ---- kaleidoscope
    kf = kaleido.render()
    for f, cell in enumerate(kf):
        for i in range(256):
            ty, tx = divmod(i, 16)
            chr_.put(KAL + f, i, cell[ty * 8:ty * 8 + 8, tx * 8:tx * 8 + 8], 'kaleido')
    files['nt_kal'] = bytes(kaleido.nametable().astype(np.uint8).flatten()) + bytes(64)
    kp = kaleido.phi_maps()
    files['phi_kring'] = bytes(kp['ring'].astype(np.uint8).flatten()) + bytes(64)
    files['phi_kspi'] = bytes(kp['spiral'].astype(np.uint8).flatten()) + bytes(64)
    files['phi_kmask'] = bytes(kp['mask'].astype(np.uint8).flatten()) + bytes(64)
    print(f'kaleido: {len(kf)} frames')

    # ---- rose window
    rimg = rose.render()
    for (b, i), t in seq_layout(rimg, ROSE).items():
        chr_.put(b, i, t, 'rose')
    rp = rose.phi_maps()
    for k in ('rad', 'ang', 'spi'):
        files['phi_r' + k] = bytes(rp[k].astype(np.uint8).flatten()) + bytes(64)
    files['nt_seq'] = bytes(p & 255 for p in range(960)) + bytes(64)

    # ---- rose tunnels (two flowers; the second one is switched in tile by tile)
    for base, name, kw in ((TUN, 'tun', dict(k=8, twist=1.6, petal=1.1)),
                           (TUN2, 'tun2', dict(k=12, twist=-1.2, petal=1.5, per_octave=8.0))):
        timg, twin = tunnel.image(**kw)
        for (b, i), t in seq_layout(timg, base).items():
            chr_.put(b, i, t, name)
        ex = bytes(((base + (p >> 8)) | (int(twin.flat[p]) << 6)) for p in range(960)) + bytes(64)
        files['ex_' + name] = ex

    # ---- sprites
    for i, t in enumerate(sprites.tiles()):
        chr_.put(SPR, i, t, 'sprites')

    (OUT / 'chr.bin').write_bytes(bytes(chr_.data))
    for k, v in files.items():
        (OUT / f'{k}.bin').write_bytes(v)
    inc = [
        '; Generated by tools/assets.py. Do not edit.',
        f'JULIA_FRAMES = {len(ex_j)}',
        f'JULIA_BANKS = {jb}',
        f'CHR_KAL = {KAL}', f'CHR_ROSE = {ROSE}', f'CHR_TUN = {TUN}', f'CHR_TUN2 = {TUN2}',
        f'CHR_BLANK = {BLANK}', f'CHR_SPR = {SPR}',
        f'KAL_FRAMES = {len(kf)}',
    ]
    # glint positions: the gold features of the rose window (petal seeds, lancet and ring roundels)
    import math
    pts = []
    for i in range(12):
        for r, off in ((29, 0), (57, 15), (94, 15), (92, 0)):
            a = math.radians(30 * i + off)
            pts.append((int(round(128 + r * math.cos(a))) - 4, int(round(120 + r * math.sin(a))) - 5))
    inc.append('.segment "RODATA"')
    inc.append('glint_n = %d' % len(pts))
    inc.append('glint_px: .byte ' + ','.join(str(x) for x, y in pts))
    inc.append('glint_py: .byte ' + ','.join(str(y) for x, y in pts))
    inc.append('.align 256')
    inc.append('sin_tab: .byte ' + ','.join(str(int(round(127 * math.sin(2 * math.pi * i / 256))) & 255) for i in range(256)))
    inc.append('.segment "CODE"')
    (OUT / 'assets.inc').write_text('\n'.join(inc) + '\n')
    if prev:
        from PIL import Image
        ramp = [0x0c, 0x1c, 0x2c, 0x3c, 0x31, 0x21, 0x11, 0x01]
        pals = [[0x0f] + [ramp[(2 * w + i) % 8] for i in range(3)] for w in range(4)]
        Image.fromarray(nes.preview(rimg, np.full((30, 32), 2), [[0x0f, 0x01, 0x06, 0x07], [0x0f, 0x02, 0x16, 0x17], [0x0f, 0x12, 0x16, 0x28], [0x0f, 0x21, 0x25, 0x38]], 2)).save(prev / 'rose.png')
        Image.fromarray(nes.preview(fr[0][0], fr[0][1], pals, 2)).save(prev / 'julia0.png')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
