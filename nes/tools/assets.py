#!/usr/bin/env python3
"""Builds every graphics asset for Cartridge into nes/out/gen/:
  chr.bin        all CHR-ROM (4 KB banks)
  *.bin          per-part data (nametable/ExRAM rows, tables)
  assets.inc     constants and metasprites for ca65
Run by nes/build.sh. Everything is procedural and deterministic."""
import os
import sys
import time
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import nespal  # noqa: E402
import convert  # noqa: E402
import scenes  # noqa: E402
import sprites  # noqa: E402
import font  # noqa: E402

OUT = os.path.join(HERE, '..', 'out', 'gen')
PREVIEW = os.environ.get('PREVIEW_DIR')
CHR_BANKS = 64

pool = convert.ChrPool(CHR_BANKS)
inc = ['; generated by nes/tools/assets.py - do not edit', '']


def const(name, val):
    inc.append(f'{name} = {val}')


def write(name, data):
    with open(os.path.join(OUT, name), 'wb') as f:
        f.write(bytes(data))


def pal_bytes(bg, bgpals, sprpals):
    out = []
    for p in bgpals:
        out += [bg] + list(p)
    for p in sprpals:
        out += [bg] + list(p)
    return out


def asm_bytes(d, label, data):
    d.append(f'{label}:')
    data = list(data)
    for i in range(0, len(data), 16):
        d.append('  .byte ' + ', '.join(f'${b:02X}' for b in data[i:i + 16]))


SPRITE_INC = []


def sprite_page(d, page):
    """Sprite CHR page + metasprites. Metasprites go to sprites.inc, linked in fixed ROM so
    any part can draw any page."""
    b = pool.alloc(1)[0]
    pool.banks[b] = [page.chr()[i * 16:i * 16 + 16] for i in range(256)]
    const(f'{page.name.upper()}_SPR', b * 4)  # first 1 KB bank number for $5124
    SPRITE_INC.append(page.asm())
    return b


def write_inc(name, d):
    with open(os.path.join(OUT, name + '.inc'), 'w') as f:
        f.write('; generated by nes/tools/assets.py - do not edit\n' + '\n'.join(d) + '\n')


def preview(name, rgb):
    if PREVIEW:
        from PIL import Image
        Image.fromarray(np.asarray(rgb, np.uint8)).save(os.path.join(PREVIEW, name + '.png'))


