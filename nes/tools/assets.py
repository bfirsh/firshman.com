def build_ground():
    d = []
    t = time.time()
    img = scenes.render_ground()
    pals = scenes.GROUND_PALS
    pix, pal = convert.quantize(img, pals, 0x0F, dith=convert.Ditherer(penalty=0.05))
    preview('ground', convert.render(pix, pal, pals, 0x0F))
    nt, ex, banks = convert.bitmap_to_chr(pix, pal, pool)
    rows = bytearray()
    for r in range(60):
        rows += nt[r * 32:r * 32 + 32] + ex[r * 32:r * 32 + 32]
    write('ground_rows.bin', rows)
    const('GROUND_BANKS', len(banks))
    # Sprites: balloon rig, sun, stars.
    page = sprites.SpritePage('ground')
    env, rig, ox, oy = sprites.balloon_rig(1.0)
    page.add_layers('balloon', [(env, 0), (rig, 1)], ox, oy)
    ridge = lambda x: scenes.ridge(x, scenes.HZ + 4, 24, 64, scenes.N2) + 5 * np.sin(x / 37.0)
    ys = list(range(int(scenes.HZ + 16), int(scenes.HZ - 28), -1))
    sprites.sun_frames(page, ridge, scenes.SUN_X, ys)
    const('SUN_FRAMES', len(ys))
    const('SUN_Y0', ys[0])
    star = np.zeros((8, 8), np.uint8)
    star[3, 3] = 3
    page.add_meta('star1', star, 3, 3, 3)
    star2 = np.zeros((8, 8), np.uint8)
    star2[3, 3] = 3
    star2[2, 3] = star2[4, 3] = star2[3, 2] = star2[3, 4] = 1
    page.add_meta('star2', star2, 3, 3, 3)
    idx, ox, oy = sprites.parachute_rig()
    page.add_meta('gchute', idx, 1, ox, oy)
    SPRITE_INC.append(f'GSTAR1_TILE = {page.metas["star1"][0][1]}')
    SPRITE_INC.append(f'GSTAR2_TILE = {page.metas["star2"][0][1]}')
    sprite_page(d, page)
    SPRITE_INC.append('sun_meta_lo: .lobytes ' + ', '.join(f'meta_sun{k}' for k in range(len(ys))))
    SPRITE_INC.append('sun_meta_hi: .hibytes ' + ', '.join(f'meta_sun{k}' for k in range(len(ys))))
    sprpals = [[0x13, 0x36, 0x30], [0x13, 0x16, 0x30], [0x27, 0x37, 0x38], [0x02, 0x32, 0x30]]
    asm_bytes(d, 'ground_palette', pal_bytes(0x0F, pals, sprpals))
    # Night -> dawn palette keyframes: each ramp colour walks from its night colour to its dawn one.
    keys = ground_keys(pals, sprpals)
    const('GROUND_KEYS', len(keys))
    for i, k in enumerate(keys):
        asm_bytes(d, f'ground_key{i}', k)
    d.append('ground_key_lo: .lobytes ' + ', '.join(f'ground_key{i}' for i in range(len(keys))))
    d.append('ground_key_hi: .hibytes ' + ', '.join(f'ground_key{i}' for i in range(len(keys))))
    write_inc('ground', d)
    print(f'ground: {len(banks)} banks, {len(set(zip(nt, ex)))} tiles, {time.time() - t:.1f}s')


NIGHT = {0x02: 0x0F, 0x03: 0x0F, 0x13: 0x02, 0x25: 0x02, 0x26: 0x03, 0x27: 0x03, 0x37: 0x13,
         0x36: 0x02, 0x30: 0x03, 0x16: 0x0F, 0x38: 0x13, 0x32: 0x22, 0x0F: 0x0F}
PREDAWN = {0x02: 0x0F, 0x03: 0x02, 0x13: 0x03, 0x25: 0x13, 0x26: 0x14, 0x27: 0x15, 0x37: 0x25,
           0x36: 0x13, 0x30: 0x23, 0x16: 0x06, 0x38: 0x26, 0x32: 0x32, 0x0F: 0x0F}
EARLY = {0x02: 0x02, 0x03: 0x03, 0x13: 0x13, 0x25: 0x14, 0x26: 0x15, 0x27: 0x25, 0x37: 0x26,
         0x36: 0x24, 0x30: 0x34, 0x16: 0x16, 0x38: 0x27, 0x32: 0x32, 0x0F: 0x0F}


def ground_keys(pals, sprpals):
    base = pal_bytes(0x0F, pals, sprpals)
    keys = []
    for m in (NIGHT, PREDAWN, EARLY, None):
        keys.append([m.get(c, c) if m else c for c in base])
    return keys


def build_tables():
    d = []
    sinv = [int(round(127 * np.sin(2 * np.pi * i / 256))) & 255 for i in range(256)]
    asm_bytes(d, 'sin_tab', sinv)
    # unsigned 0..255 smoothstep ease
    asm_bytes(d, 'ease_tab', [int(round(255 * (t * t * (3 - 2 * t)))) for t in np.arange(256) / 255])
    # title unfold: 64/zoom, ease-out-back over 128 frames
    zt = []
    for i in range(128):
        p = (i + 1) / 128.0
        z = 1 + 2.4 * (p - 1) ** 3 + 1.4 * (p - 1) ** 2
        zt.append(255 if z < 0.26 else int(min(255, max(40, round(64 / z)))))
    asm_bytes(d, 'ti_zoom', zt)
    write_inc('tables', d)


def build_title():
    d = []
    img = scenes.render_title()
    pals = scenes.TITLE_PALS
    pix, pal = convert.quantize(img, pals, 0x0F, dith=convert.Ditherer(penalty=0.06))
    preview('title', convert.render(pix, pal, pals, 0x0F))
    nt, ex, banks = convert.bitmap_to_chr(pix, pal, pool)
    write('title_nt.bin', nt + bytes(64))
    write('title_ex.bin', ex + bytes(64))
    asm_bytes(d, 'title_palette', pal_bytes(0x0F, pals, [[0x02, 0x22, 0x30]] * 4))
    write_inc('title', d)
    print(f'title: {len(banks)} banks')


def build_clouds():
    d = []
    img = scenes.render_clouds()
    pals = [[0x12, 0x11, 0x21], [0x21, 0x31, 0x30], [0x0C, 0x13, 0x22], [0x32, 0x36, 0x20]]
    pix, pal = convert.quantize(img, pals, scenes.CLOUD_BG, dith=convert.Ditherer(penalty=0.06))
    preview('clouds', convert.render(pix, pal, pals, scenes.CLOUD_BG))
    nt, ex, banks = convert.bitmap_to_chr(pix, pal, pool)
    write('clouds_nt.bin', nt + bytes(64))
    write('clouds_ex.bin', ex + bytes(64))
    sprpals = [[0x22, 0x32, 0x30], [0x12, 0x16, 0x30], [0x37, 0x38, 0x30], [0x21, 0x31, 0x30]]
    asm_bytes(d, 'clouds_palette', pal_bytes(scenes.CLOUD_BG, pals, sprpals))
    # deeper sky as the climb goes on
    deep = pal_bytes(scenes.CLOUD_BG, [[0x0C, 0x12, 0x11], [0x11, 0x21, 0x31], [0x0C, 0x13, 0x22], [0x32, 0x36, 0x20]], sprpals)
    asm_bytes(d, 'clouds_palette2', deep)
    hz = scenes.CLOUD_HZ
    spd = [0] * 256
    for sline in range(240):
        w = max(0.0, (sline - hz) / (240.0 - hz))
        spd[sline] = int(min(255, round(255 * w ** 1.15)))
    asm_bytes(d, 'cl_spd', spd)
    write_inc('clouds', d)
    print(f'clouds: {len(banks)} banks')


def build_fx():
    """Chunky tile sets for the real-time effects and their textures.
    Set A: 2x2 chunks of 4x4 px, 4 colours each: tile = c00 | c10<<2 | c01<<4 | c11<<6.
    Set B: two 4x8 px chunks, 16 dithered levels each: tile = left | right<<4."""
    d = []
    ba, bb = pool.alloc(2)
    for t in range(256):
        c = [(t >> 0) & 3, (t >> 2) & 3, (t >> 4) & 3, (t >> 6) & 3]
        px = np.zeros((8, 8), np.uint8)
        px[0:4, 0:4] = c[0]
        px[0:4, 4:8] = c[1]
        px[4:8, 0:4] = c[2]
        px[4:8, 4:8] = c[3]
        pool.put(ba, t, convert.tile_bytes(px))
    b4 = np.array([[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]) / 16.0
    bayer = np.vstack([b4, b4[::-1]])  # 8 x 4
    for t in range(256):
        px = np.zeros((8, 8), np.uint8)
        for half, lv in ((0, t & 15), (1, t >> 4)):
            pos = lv / 15.0 * 3.0  # 0..3 along the 4 colours
            lo = min(int(pos), 2)
            f = pos - lo
            blk = np.where(bayer < f - 1e-9, lo + 1, lo).astype(np.uint8)
            px[:, half * 4:half * 4 + 4] = blk
        pool.put(bb, t, convert.tile_bytes(px))
    const('FX_CHR_A', ba * 4)
    const('FX_CHR_B', bb * 4)
    # Texture 1: a field of balloons (16x16 texels, 4 colours, indexed 16*v+u).
    tex = np.zeros((16, 16), np.uint8)
    yy, xx = np.mgrid[0:16, 0:16]
    tex[:] = 1
    tex[((xx + yy) // 8) % 2 == 0] = 0
    body = ((xx - 7.5) / 5.2) ** 2 + ((yy - 6.0) / 6.0) ** 2 < 1
    tex[body] = 3
    tex[body & (((xx - 5.5) ** 2 + (yy - 3.5) ** 2) > 6.5) & (xx > 8)] = 2
    tex[(xx == 7) & (yy >= 12) & (yy <= 13)] = 2
    tex[(yy == 14) & (xx >= 6) & (xx <= 8)] = 3
    t1 = tex.ravel()
    # Texture 2: concentric rings / checker for the second pass.
    r = np.hypot(xx - 7.5, yy - 7.5)
    t2 = ((r // 2.2).astype(int) % 4).astype(np.uint8)
    t2 = np.where(((xx // 4 + yy // 4) % 2 == 0) & (r > 7.4), 1, t2).astype(np.uint8).ravel()
    asm_bytes(d, 'fx_tex1', t1)
    asm_bytes(d, 'fx_tex2', t2)
    # Plasma colour ramp: 256 entries of 0..15, a smooth triangle wave.
    ramp_ = [int(round(7.5 + 7.49 * np.sin(2 * np.pi * i / 256))) for i in range(256)]
    asm_bytes(d, 'fx_ramp', ramp_)
    write_inc('fx', d)


def build_strat():
    d = []
    img = scenes.render_earth()
    pals = [[0x02, 0x21, 0x31], [0x21, 0x31, 0x30], [0x01, 0x11, 0x30], [0x01, 0x18, 0x31]]
    pix, pal = convert.quantize(img, pals, 0x0F, dith=convert.Ditherer(penalty=0.05))
    preview('earth', convert.render(pix, pal, pals, 0x0F))
    nt, ex, banks = convert.bitmap_to_chr(pix, pal, pool)
    write('earth_nt.bin', nt + bytes(64))
    write('earth_ex.bin', ex + bytes(64))
    page = sprites.SpritePage('space')
    for k, sc in enumerate((1.3, 1.55, 1.8)):
        env, rig, ox, oy = sprites.balloon_rig(sc)
        # in space the rig hangs lower: keep the same rig art
        page.add_layers(f'bal{k}', [(env, 0), (rig, 1)], ox, oy)
    sprites.burst_fragments(page)
    idx, ox, oy = sprites.parachute_rig()
    page.add_meta('chute', idx, 1, ox, oy)
    idx, ox, oy = sprites.parachute_rig(0.35)
    page.add_meta('chute_s', idx, 1, ox, oy)
    for k, r in enumerate((9.5, 5.5, 3.5)):
        idx, ox, oy = sprites.flare_disc(r)
        page.add_meta(f'flare{k}', idx, 3, ox, oy)
    sun = np.zeros((16, 16), np.uint8)
    yy, xx = np.mgrid[0:16, 0:16]
    dd = np.hypot(xx - 7.5, yy - 7.5)
    sun[dd < 7.5] = 1
    sun[dd < 5.5] = 2
    sun[dd < 3.5] = 3
    sun[(np.abs(xx - 7.5) < 1) | (np.abs(yy - 7.5) < 1)] = np.maximum(sun[(np.abs(xx - 7.5) < 1) | (np.abs(yy - 7.5) < 1)], 1)
    page.add_meta('sunbig', sun, 2, 8, 8)
    star = np.zeros((8, 8), np.uint8)
    star[3, 3] = 3
    page.add_meta('sstar1', star, 3, 3, 3)
    star2 = star.copy()
    star2[2, 3] = star2[4, 3] = star2[3, 2] = star2[3, 4] = 2
    page.add_meta('sstar2', star2, 3, 3, 3)
    SPRITE_INC.append(f'SSTAR_TILE = {page.metas["sstar1"][0][1]}')
    sprite_page(d, page)
    sprpals = [[0x2D, 0x10, 0x30], [0x2D, 0x16, 0x30], [0x27, 0x38, 0x30], [0x2D, 0x3C, 0x30]]
    asm_bytes(d, 'strat_palette', pal_bytes(0x0F, pals, sprpals))
    write_inc('strat', d)
    print(f'strat: {len(banks)} banks')


def build_climax():
    """The turning globe: 32 frames of 16x16 tiles, one 4 KB bank each (tile index = position),
    with one palette per position chosen over all frames so a frame change only rewrites the
    bank bits. Plus the space/font bank around it."""
    d = []
    t = time.time()
    n = scenes.GLOBE_FRAMES
    pals = scenes.GLOBE_PALS
    dith = convert.Ditherer(penalty=0.05)
    frames = [scenes.render_globe(k) for k in range(n)]
    tiles = [convert.tiles_of(f) for f in frames]
    err = np.zeros((256, 4))
    yy, xx = np.mgrid[0:8, 0:8]
    for f in range(n):
        for i, (ty, tx, tl) in enumerate(tiles[f]):
            for p in range(4):
                err[i, p] += dith.tile_error_and_pixels(tl, [0x0F] + pals[p], (yy + ty * 8).ravel(), (xx + tx * 8).ravel())[0]
    force = err.argmin(1).reshape(16, 16)
    banks = pool.alloc(n)
    for f in range(n):
        pix, pal = convert.quantize(frames[f], pals, 0x0F, dith=dith, force=force)
        if f == 0:
            preview('globe0', convert.render(pix, pal, pals, 0x0F))
        for i in range(256):
            ty, tx = divmod(i, 16)
            pool.put(banks[f], i, convert.tile_bytes(pix[ty * 8:ty * 8 + 8, tx * 8:tx * 8 + 8]))
    const('GLOBE_BANK0', banks[0])
    asm_bytes(d, 'globe_pal', [int(p) << 6 for p in force.ravel()])
    # space + font bank: tile 0 black, 1-4 stars, then tall glyphs (top at 16+i, bottom at 80+i)
    sb = pool.alloc(1)[0]
    pool.put(sb, 0, bytes(16))
    for k, pts in enumerate(([(3, 3, 3)], [(4, 2, 1)], [(2, 5, 2)], [(3, 3, 3), (2, 3, 1), (4, 3, 1), (3, 2, 1), (3, 4, 1)])):
        tt = np.zeros((8, 8), np.uint8)
        for y, x, c in pts:
            tt[y, x] = c
        pool.put(sb, 1 + k, convert.tile_bytes(tt))
    for i, ch in enumerate(font.CHARS):
        top, bot = font.tall_tiles(ch)
        pool.put(sb, 16 + i, convert.tile_bytes(top))
        pool.put(sb, 80 + i, convert.tile_bytes(bot))
    const('SPACE_BANK', sb)
    # star map for the rest of the screen
    rng = np.random.default_rng(5)
    nt = bytearray(960)
    ex = bytearray(960)
    for i in range(960):
        r, c = divmod(i, 32)
        if 5 <= r < 21 and 8 <= c < 24:
            nt[i] = (r - 5) * 16 + (c - 8)
            ex[i] = banks[0] | (int(force[r - 5, c - 8]) << 6)
        else:
            nt[i] = int(rng.choice([1, 2, 3, 4])) if rng.random() < 0.18 else 0
            ex[i] = sb | (1 << 6)
    write('globe_nt.bin', bytes(nt) + bytes(64))
    write('globe_ex.bin', bytes(ex) + bytes(64))
    asm_bytes(d, 'climax_palette', pal_bytes(0x0F, pals, [[0x2D, 0x10, 0x30], [0x2D, 0x16, 0x30], [0x21, 0x31, 0x30], [0x2D, 0x3C, 0x30]]))
    # text: map characters to glyph numbers
    txt = open(os.path.join(HERE, '..', 'src', 'greets.txt')).read().upper()
    txt = ' '.join(txt.split()) + '          '
    codes = [font.CHARS.index(c) if c in font.CHARS else 0 for c in txt]
    asm_bytes(d, 'cx_text', codes + [255])
    write_inc('climax', d)
    print(f'climax: {n}+1 banks, {len(txt)} chars of text, {time.time() - t:.1f}s')


def main():
    os.makedirs(OUT, exist_ok=True)
    build_climax()
    build_strat()
    build_fx()
    build_clouds()
    build_tables()
    build_title()
    build_ground()
    write_inc('sprites', SPRITE_INC)
    const('CHR_USED', pool.used())
    write('chr.bin', pool.blob(CHR_BANKS))
    with open(os.path.join(OUT, 'assets.inc'), 'w') as f:
        f.write('\n'.join(inc) + '\n')
    print(f'CHR: {pool.used()} of {CHR_BANKS} banks')


if __name__ == '__main__':
    main()
