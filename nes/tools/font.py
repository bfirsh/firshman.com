def glyph(ch):
    g = GLYPHS[ch]
    return np.array([[1 if c == '#' else 0 for c in row] for row in g], np.uint8)


def tall_tiles(ch):
    """8x16 version: the 5x7 glyph doubled vertically, colour 3 with a colour-1 drop shadow and a
    colour-2 lower half (a little sheen). Returns (top 8x8, bottom 8x8)."""
    g = glyph(ch)
    big = np.zeros((16, 8), np.uint8)
    for y in range(7):
        for x in range(5):
            if g[y, x]:
                for yy in (2 * y + 1, 2 * y + 2):
                    big[yy, x + 1] = 3 if yy < 8 else 2
    sh = np.zeros_like(big)
    sh[1:, 1:] = big[:-1, :-1]
    out = np.where(big > 0, big, np.where(sh > 0, 1, 0)).astype(np.uint8)
    return out[:8], out[8:]


def small_tile(ch):
    g = glyph(ch)
    t = np.zeros((8, 8), np.uint8)
    t[0:7, 1:6] = g * 3
    sh = np.zeros_like(t)
    sh[1:, 1:] = t[:-1, :-1]
    return np.where(t > 0, 3, np.where(sh > 0, 1, 0)).astype(np.uint8)
