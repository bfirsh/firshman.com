const cache = new Map<string, Bmp>();
function glyph(ch: string): Bmp {
  let g = cache.get(ch);
  if (g) return g;
  const rows = (RAW[ch] ?? RAW['?']).split('|');
  let w = 0;
  for (const r of rows) w = Math.max(w, r.lastIndexOf('#') + 1);
  const d = new Uint8Array(w * 8);
  rows.forEach((r, y) => {
    for (let x = 0; x < w; x++) if (r[x] === '#') d[y * w + x] = 1;
  });
  g = { w, h: 8, d };
  cache.set(ch, g);
  return g;
}

/** 1-bit mask of a line of text (proportional, 1px gap). xs[i] is the x of char i. */
export function textMask(text: string, gap = 1): { m: Bmp; xs: number[] } {
  const t = text.toUpperCase();
  const xs: number[] = [];
  let w = 0;
  const gs = [...t].map((c) => {
    xs.push(w);
    const g = c === ' ' ? null : glyph(c);
    w += (g ? g.w : 3) + gap;
    return g;
  });
  w = Math.max(1, w);
  const d = new Uint8Array(w * 8);
  gs.forEach((g, i) => {
    if (!g) return;
    const x0 = xs[i];
    for (let y = 0; y < 8; y++) for (let x = 0; x < g.w; x++) if (g.d[y * g.w + x]) d[y * w + x0 + x] = 1;
  });
  return { m: { w, h: 8, d }, xs };
}

const at = (b: Bmp, x: number, y: number) => (x < 0 || y < 0 || x >= b.w || y >= b.h ? 0 : b.d[y * b.w + x]);

export function scale2x(b: Bmp): Bmp {
  const w = b.w * 2, h = b.h * 2, d = new Uint8Array(w * h);
  for (let y = 0; y < b.h; y++)
    for (let x = 0; x < b.w; x++) {
      const P = at(b, x, y), A = at(b, x, y - 1), B = at(b, x + 1, y), C = at(b, x - 1, y), D = at(b, x, y + 1);
      const o = y * 2 * w + x * 2;
      d[o] = C === A && C !== D && A !== B ? A : P;
      d[o + 1] = A === B && A !== C && B !== D ? B : P;
      d[o + w] = D === C && D !== B && C !== A ? C : P;
      d[o + w + 1] = B === D && B !== A && D !== C ? D : P;
    }
  return { w, h, d };
}

export function scale3x(b: Bmp): Bmp {
  const w = b.w * 3, h = b.h * 3, d = new Uint8Array(w * h);
  for (let y = 0; y < b.h; y++)
    for (let x = 0; x < b.w; x++) {
      const A = at(b, x - 1, y - 1), B = at(b, x, y - 1), C = at(b, x + 1, y - 1);
      const D = at(b, x - 1, y), E = at(b, x, y), F = at(b, x + 1, y);
      const G = at(b, x - 1, y + 1), H = at(b, x, y + 1), I = at(b, x + 1, y + 1);
      const o = y * 3 * w + x * 3;
      let e0 = E, e1 = E, e2 = E, e3 = E, e5 = E, e6 = E, e7 = E, e8 = E;
      if (B !== H && D !== F) {
        e0 = D === B ? D : E;
        e1 = (D === B && E !== C) || (B === F && E !== A) ? B : E;
        e2 = B === F ? F : E;
        e3 = (D === B && E !== G) || (D === H && E !== A) ? D : E;
        e5 = (B === F && E !== I) || (H === F && E !== C) ? F : E;
        e6 = D === H ? D : E;
        e7 = (D === H && E !== I) || (H === F && E !== G) ? H : E;
        e8 = H === F ? F : E;
      }
      d[o] = e0; d[o + 1] = e1; d[o + 2] = e2;
      d[o + w] = e3; d[o + w + 1] = E; d[o + w + 2] = e5;
      d[o + 2 * w] = e6; d[o + 2 * w + 1] = e7; d[o + 2 * w + 2] = e8;
    }
  return { w, h, d };
}

/** Colour a mask: gradient by row, 1px highlight on top edges, 1px outline all round. */
export function shade(m: Bmp, row: (r: number) => number, outline: number, hi: number): Bmp {
  const w = m.w + 2, h = m.h + 2, d = new Uint8Array(w * h);
  for (let y = 0; y < h; y++)
    for (let x = 0; x < w; x++) {
      const mx = x - 1, my = y - 1;
      if (at(m, mx, my)) d[y * w + x] = at(m, mx, my - 1) ? row(my) : hi;
      else if (
        at(m, mx - 1, my) || at(m, mx + 1, my) || at(m, mx, my - 1) || at(m, mx, my + 1) ||
        at(m, mx - 1, my - 1) || at(m, mx + 1, my - 1) || at(m, mx - 1, my + 1) || at(m, mx + 1, my + 1)
      )
        d[y * w + x] = outline;
    }
  return { w, h, d };
}

/** Rows used by glyph bodies at scale s (the 8th row is only for descenders). */
export const bodyRows = (s: number) => 7 * s;
