export function pixelSvg(rows: string[], className = ""): string {
  let ink = "";
  let paper = "";
  rows.forEach((row, y) => {
    for (let x = 0; x < 16; x++) {
      const c = row[x];
      const cell = `M${x} ${y}h1v1h-1z`;
      if (c === "#") ink += cell;
      else if (c === "o") paper += cell;
      else if (c === "+") {
        if ((x + y) % 2 === 0) ink += cell;
        else paper += cell;
      }
    }
  });
  return `<svg class="${className}" viewBox="0 0 16 16" width="16" height="16" aria-hidden="true" shape-rendering="crispEdges"><path class="px-paper" fill="#fff" d="${paper}"/><path class="px-ink" fill="#000" d="${ink}"/></svg>`;
}
